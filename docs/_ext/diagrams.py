"""Sphinx directive ``diagram``: a diagram drawn in a light and a dark variant.

The diagrams are generated by ``docs/_diagrams/make_diagrams.py`` as
``_static/diagrams/<name>.svg`` (light theme) and ``<name>_dark.svg`` (dark
theme). The directive emits one figure holding both images, with the classes
``only-light`` and ``only-dark`` that pydata-sphinx-theme shows in the
matching theme, and the content of the directive as caption (parsed, so it
may hold math and roles)::

    ```{diagram} rresnet_block
    :alt: The residual block, step by step
    :width: 100%

    Caption with $X_{i+1} = \\mathrm{Exp}_{X_i}(\\hat V)$.
    ```

A missing file is a build warning (an error with ``-W``).
"""

from __future__ import annotations

from pathlib import Path
from typing import ClassVar

from docutils import nodes
from docutils.parsers.rst import directives
from sphinx.util import logging
from sphinx.util.docutils import SphinxDirective


logger = logging.getLogger(__name__)


class Diagram(SphinxDirective):
    required_arguments = 1
    has_content = True
    option_spec: ClassVar[dict] = {
        "alt": directives.unchanged,
        "width": directives.unchanged,
    }

    def run(self) -> list[nodes.Node]:
        name = self.arguments[0].strip()
        folder = Path(self.env.srcdir) / "_static" / "diagrams"
        missing = [
            f for f in (f"{name}.svg", f"{name}_dark.svg") if not (folder / f).is_file()
        ]
        if missing:
            logger.warning(
                "diagram: missing %s in _static/diagrams",
                ", ".join(missing),
                location=self.get_location(),
            )
            return []
        alt = self.options.get("alt", name.replace("_", " "))
        figure = nodes.figure(classes=["spd-diagram"])
        if "width" in self.options:
            figure["width"] = self.options["width"]
        for suffix, cls in (("", "only-light"), ("_dark", "only-dark")):
            figure += nodes.image(
                uri=f"/_static/diagrams/{name}{suffix}.svg",
                alt=alt,
                classes=[cls],
                width=self.options.get("width", "100%"),
            )
        if self.content:
            caption = nodes.caption()
            parsed = nodes.paragraph()
            self.state.nested_parse(self.content, self.content_offset, parsed)
            # a caption holds inline text: unwrap the parsed paragraph(s)
            for para in parsed.children:
                caption.extend(
                    para.children if isinstance(para, nodes.paragraph) else [para]
                )
            figure += caption
        return [figure]


def setup(app):
    app.add_directive("diagram", Diagram)
    return {"parallel_read_safe": True, "parallel_write_safe": True}
